"""End-to-end test of the Fleet-DT stack on one host.

Two vessel brokers (patched Mosquitto 2.1 with the vessel regulator plugin in mode paper, demand
external), the GS broker with the two bridges per vessel generated by fleetdt.gsconf, the DTI program
(with the jitter allowance of the regulator) and the synthetic load of each vessel, the channel monitor
replaying counters with a drop of the channel, the AS, and the VE collector that assembles G(t). The
test checks Algorithm 1 against G(t), the policing bound r <= d, the delivery of every forwarded message
within its step, the admission of fewer video layers (dtp.json: 16 stripe layer topics) after the drop of
C_hat(t), and the Section VI metrics of the resulting DTA (criterion count).

Needs MOSQ (default /opt/mosquitto-2.1) and the C programs in FDT_BUILD (default build/).

With FDT_VESSEL_EXEC (a command prefix, e.g. "podman exec fdt-rpi10"), the vessel programs (vessel
brokers, DTI programs, synthetic load) run through that prefix, with FDT_VESSEL_BUILD,
FDT_VESSEL_MOSQ and FDT_VESSEL_PYTHON for their binaries: tests/armhf/run.sh runs them in an emulated
Raspbian 10 (armhf, gcc 8.3, Python 3.7) while the GS programs run on the host.
"""
import json
import math
import os
import shutil
import socket
import subprocess
import sys
import time
from pathlib import Path

import pytest

from fleetdt.analysis import analyze
from fleetdt.as_model import DTP, admission
from fleetdt.gsconf import gs_conf, vessel_conf
from fleetdt.model import Graph
from fleetdt.ve.collector import Assembler, MqttCollector, StepClock

ROOT = Path(__file__).resolve().parents[1]
MOSQ = Path(os.environ.get("MOSQ", "/opt/mosquitto-2.1"))
BUILD = Path(os.environ.get("FDT_BUILD", ROOT / "build"))
BROKER = MOSQ / "sbin" / "mosquitto"
RUN_S = float(os.environ.get("FDT_IT_SECONDS", "24"))
VEXEC = os.environ.get("FDT_VESSEL_EXEC", "").split()
VBUILD = Path(os.environ.get("FDT_VESSEL_BUILD", BUILD))
VBROKER = Path(os.environ.get("FDT_VESSEL_MOSQ", MOSQ)) / "sbin" / "mosquitto"
VPYTHON = os.environ.get("FDT_VESSEL_PYTHON", sys.executable)

pytestmark = pytest.mark.skipif(not (BROKER.exists() and (VBUILD / "fdt_regulator.so").exists()
                                     and (VBUILD / "fdt_dti").exists() and (BUILD / "fdt_chmon").exists()),
                                reason="needs the patched Mosquitto and make")

Y_HIGH, Y_LOW = 351_000.0, 99_000.0   # y(t) of the replayed counters: busy 8 ms and 92 ms per step
JITTER_MS = 2.0                        # plugin_opt_jitter_ms of the regulators and --jitter-ms of fdt_dti


def free_port() -> int:
    s = socket.socket()
    s.bind(("127.0.0.1", 0))
    p = s.getsockname()[1]
    s.close()
    return p


def wait_port(port: int, timeout: float = 30.0) -> None:
    end = time.time() + timeout
    while time.time() < end:
        try:
            socket.create_connection(("127.0.0.1", port), 0.2).close()
            return
        except OSError:
            time.sleep(0.05)
    raise TimeoutError("port %d" % port)


def counters(path: Path, phases) -> None:
    """Survey samples with 125 ms of channel time per step and the busy time of each phase."""
    at, time_ms, busy = 1_000_000.0, 0, 0
    with open(path, "w") as f:
        for steps, busy_ms in phases:
            for _ in range(steps):
                f.write(json.dumps({"at": at, "survey": 1, "time_ms": time_ms, "busy_ms": busy,
                                    "rx_bytes": 0, "tx_bytes": 0, "rx_packets": 0, "tx_packets": 0,
                                    "tx_failed": 0}) + "\n")
                at += 0.125
                time_ms += 125
                busy += busy_ms


@pytest.fixture
def stack(tmp_path):
    procs = []
    logs = []

    def spawn(name, args, env=None, vessel=False):
        log = open(tmp_path / ("%s.log" % name), "w")
        logs.append((name, tmp_path / ("%s.log" % name)))
        p = subprocess.Popen((VEXEC if vessel else []) + [str(a) for a in args], stdout=log, stderr=subprocess.STDOUT, cwd=str(ROOT),
                             env=dict(os.environ, PYTHONPATH=str(ROOT), **(env or {})))
        procs.append((name, p))
        return p

    yield tmp_path, spawn, logs
    for name, p in reversed(procs):
        if p.poll() is None:
            p.terminate()
    for name, p in reversed(procs):
        try:
            p.wait(5)
        except subprocess.TimeoutExpired:
            p.kill()


def test_stack(stack):
    tmp, spawn, logs = stack
    # dtp.json with smaller video (8 frames per second, frame cap 8000 bytes): under the cost bound of the
    # paper (eq. cons, h_W of the 802.11g PHY) a QoS 0 message costs about 1.3 kB of channel bytes besides its
    # content, so the telemetry of a vessel takes 23000 bytes per step; with these stripes b(t) admits the 16
    # layers at Y_HIGH and 3 at Y_LOW
    sys.path.insert(0, str(ROOT / "vessel" / "publishers"))
    import video_layers
    raw = video_layers.with_video(json.loads((ROOT / "dtp.json").read_text()), fps=8.0, frame_cap=8000)
    raw["epoch"] = None
    raw["vessels"] = [1, 2]
    dtp_path = tmp / "dtp.json"
    dtp_path.write_text(json.dumps(raw))
    dtp = DTP.from_dict(raw)

    gs_port = free_port()
    vp = {i: (free_port(), free_port()) for i in (1, 2)}
    for i, (cp, dp) in vp.items():
        conf = tmp / ("vessel%d.conf" % i)
        conf.write_text(vessel_conf(i, str(dtp_path), plugin=str(VBUILD / "fdt_regulator.so"), port=cp,
                                    data_port=dp, bind="127.0.0.1", stats_s=5, log_dest="stdout", mode="paper",
                                    demand="external", jitter_ms=JITTER_MS)
                        + "user root\n")   # started as root, the broker would drop to nobody and not read FDT_BUILD
        spawn("broker-b%d" % i, [VBROKER, "-c", conf], vessel=True)
        wait_port(cp)
    gconf = tmp / "gs.conf"
    gconf.write_text(gs_conf({i: "127.0.0.1,%d,%d" % v for i, v in vp.items()}, listen="127.0.0.1:%d" % gs_port)
                     + "log_dest stdout\nuser root\n")
    spawn("broker-gs", [BROKER, "-c", gconf])
    wait_port(gs_port)

    # channel: 64 steps high, 80 steps low, then high again (looped)
    samples = tmp / "samples.jsonl"
    counters(samples, [(64, 8), (80, 92), (200, 8)])
    spawn("chmon", [BUILD / "fdt_chmon", "--dtp", dtp_path, "--replay", samples, "--loop", "--prio", "0",
                    "--broker", "127.0.0.1:%d" % gs_port])
    spawn("as", [sys.executable, "-m", "fleetdt.as_service", "--dtp", dtp_path, "--broker", "127.0.0.1:%d" % gs_port,
                 "--log", tmp / "as.jsonl", "-v"])

    graphs = []
    asm = Assembler(dtp, StepClock(dtp.Ts, dtp.t0))
    col = MqttCollector(asm, graphs.append, "127.0.0.1", gs_port)
    col.start()
    time.sleep(2.0)   # bridges connected
    for i, (cp, dp) in vp.items():
        spawn("dti-b%d" % i, [VBUILD / "fdt_dti", "--dtp", dtp_path, "--vessel", i, "--broker", "127.0.0.1:%d" % cp,
                              "--prio", "0", "--idle", "4", "--jitter-ms", JITTER_MS], vessel=True)
        spawn("load-b%d" % i, [VPYTHON, ROOT / "vessel" / "publishers" / "raw_load.py", "--dtp", dtp_path,
                               "--vessel", i, "--port", cp, "--seed", 7], vessel=True)
    time.sleep(RUN_S)
    col.stop()
    with open(tmp / "dta.jsonl", "w") as f:
        for g in graphs:
            f.write(json.dumps(g.to_dict()) + "\n")
    shutil.copy(tmp / "dta.jsonl", "/tmp/fdt_it_dta.jsonl") if os.environ.get("FDT_IT_KEEP") else None

    def show_logs():
        return "\n".join("== %s\n%s" % (n, p.read_text()[-1500:]) for n, p in logs)

    # steady part: after the first 2 s of load
    t_load = graphs[0].t + int(2.0 / dtp.Ts) if graphs else 0
    steady = [g for g in graphs if g.t >= t_load + 16]
    assert len(steady) > 0.6 * RUN_S / dtp.Ts, show_logs()

    full = [g for g in steady if g.vessels == [1, 2]]
    assert len(full) >= 0.95 * len(steady), show_logs()

    layers = [dtp.index(n) for n in dtp.topics if n.startswith("video_")]
    assert len(layers) == 16
    n_checked = 0
    n_edges = n_exact = 0
    by_C = {"high": [], "low": []}      # admitted layers per step, by the level of C_hat(t)
    for g in full:
        D = {i: [g.edge(i, l).d for l in range(1, dtp.L + 1)] for i in g.vessels}
        p = [g.edge(1, l).p for l in range(1, dtp.L + 1)]
        if None in p or g.b is None:
            continue
        # Algorithm 1 reproduced from G(t)
        assert admission(D, g.order, g.needed, g.b) == p, (g.t, D, g.b, p)
        n_checked += 1
        for e in g.edges:
            assert e.dup == 0
            assert e.r <= e.d + 1, (g.t, e)               # policing: r_{i,l}(t) <= d_{i,l}(t)
            if (e.p or 0) == 0:
                assert e.n == 0, (g.t, e)                  # withheld topics send nothing
            if e.fwd is not None:
                n_edges += 1
                n_exact += int(e.n == e.fwd and e.late == 0)
        k = sum(1 for l in layers if p[l - 1] > 0)
        # stripe layers of different demands: a layer after the first rejected one is admitted only when
        # its demand is smaller than that of the rejected layer for some vessel (Algorithm 1, line 7)
        rej = [l for l in layers if p[l - 1] == 0]
        for l in layers:
            if rej and l > rej[0] and p[l - 1] > 0:
                assert any(D[i][l - 1] < D[i][rej[0] - 1] for i in D), (g.t, l, rej[0], p)
        if k < len(layers):          # a rejected layer: the demand of a vessel exceeds b(t)
            assert g.b < max(sum(D[i]) for i in D) + 1, (g.t, g.b)
        by_C["high" if g.C_hat > (Y_HIGH + Y_LOW) / 2 else "low"].append(k)
    assert n_checked >= 0.9 * len(full), show_logs()
    assert len(by_C["high"]) > 20 and len(by_C["low"]) > 20, ({k: len(v) for k, v in by_C.items()}, show_logs())
    mean = {k: sum(v) / len(v) for k, v in by_C.items()}
    assert mean["high"] > mean["low"] + 1, mean              # fewer layers after the drop of C_hat(t)
    assert n_edges > 0 and n_exact >= 0.98 * n_edges, (n_exact, n_edges, show_logs())

    ys = [g.y for g in steady if g.y is not None]
    assert len(ys) >= 0.9 * len(steady)
    assert all(abs(y - Y_HIGH) < 1 or abs(y - Y_LOW) < 1 for y in ys), sorted(set(ys))[:10]

    res = analyze([g.to_dict() for g in steady], dtp, criterion="count", ci=False)
    assert res["delta"]["value"] >= 0.95, res["delta"]
    assert res["mu"]["value"] <= 0.01, res["mu"]
    assert res["phi"]["value"] >= 0.95, res["phi"]
    dec = [json.loads(l) for l in (tmp / "as.jsonl").read_text().splitlines()]
    assert sum(1 for d in dec if d.get("published")) >= 0.9 * len(steady)
