#include "worldgen/worldgen.h"

#include "webots/fdt_webots_fleet.h"

#include <ctype.h>
#include <stdarg.h>
#include <stdio.h>
#include <string.h>

/** Markers that delimit the two hull blocks of jundia_fleet.wbt. */
#define MARK_V0  "# Vessel 0."
#define MARK_V1  "# Vessel 1."
#define DEF_V1   "DEF TILAPIA Robot {"
#define NAME_V1  "name \"Tilapia\""
#define TRANS    "translation "

/** Grid origin: east of vessel 0, north of every obstacle of the world. */
#define GRID_EAST_M  (-15.44)
#define GRID_NORTH_M 14.0
#define HULL_UP_M    0.199426

typedef struct {
    char  *buf;
    size_t cap;
    size_t len;
    int    full;
} sink_t;

static void put(sink_t *s, const char *p, size_t n)
{
    if (s->full || s->len + n + 1 > s->cap) {
        s->full = 1;
        return;
    }
    memcpy(s->buf + s->len, p, n);
    s->len += n;
    s->buf[s->len] = '\0';
}

static void putf(sink_t *s, const char *fmt, ...)
{
    char tmp[256];
    va_list ap;
    va_start(ap, fmt);
    const int n = vsnprintf(tmp, sizeof tmp, fmt, ap);
    va_end(ap);
    if (n < 0 || (size_t)n >= sizeof tmp) {
        s->full = 1;
        return;
    }
    put(s, tmp, (size_t)n);
}

/** The display name: the DEF name with only its first letter in capitals. */
static void display_name(const char *def, char *out, size_t cap)
{
    size_t i = 0;
    for (; def[i] != '\0' && i + 1 < cap; i++) {
        out[i] = (char)((i == 0) ? def[i] : tolower((unsigned char)def[i]));
    }
    out[i] = '\0';
}

/** Emits vessel @p k from the vessel 1 body, renamed and moved. */
static void emit_copy(sink_t *s, const char *body, size_t len, size_t k)
{
    char def[32];
    char name[32];
    (void)fdt_webots_vessel_def(k, def, sizeof def);
    display_name(def, name, sizeof name);

    const size_t slot = k - 2;
    const double east  = GRID_EAST_M +
        FDT_WBTGEN_SPACING_M * (double)(slot % FDT_WBTGEN_COLUMNS);
    const double north = GRID_NORTH_M +
        FDT_WBTGEN_SPACING_M * (double)(slot / FDT_WBTGEN_COLUMNS);

    putf(s, "# Vessel %zu, generated: a copy of vessel 1.\n", k);

    const char *end = body + len;
    const char *p = body;
    int moved = 0;
    while (p < end) {
        const char *nl = memchr(p, '\n', (size_t)(end - p));
        const char *eol = (nl != NULL) ? nl + 1 : end;
        const size_t n = (size_t)(eol - p);

        const char *lead = p;
        while (lead < eol && *lead == ' ') {
            lead++;
        }

        if (strncmp(p, DEF_V1, strlen(DEF_V1)) == 0) {
            putf(s, "DEF %s Robot {\n", def);
        } else if (!moved && lead == p + 2 &&
                   strncmp(lead, TRANS, strlen(TRANS)) == 0) {
            putf(s, "  translation %.5f %.5f %.6f\n", east, north, HULL_UP_M);
            moved = 1;
        } else if (strncmp(lead, NAME_V1, strlen(NAME_V1)) == 0) {
            putf(s, "  name \"%s\"\n", name);
        } else {
            put(s, p, n);
        }
        p = eol;
    }
}

long fdt_wbtgen(const char *tmpl, unsigned n, char *out, size_t cap)
{
    if (tmpl == NULL || out == NULL || cap == 0 || n == 0 ||
        n > FDT_WEBOTS_MAX_VESSELS) {
        return -1;
    }

    const char *v0 = strstr(tmpl, MARK_V0);
    const char *v1 = (v0 != NULL) ? strstr(v0, MARK_V1) : NULL;
    const char *d1 = (v1 != NULL) ? strstr(v1, DEF_V1) : NULL;
    const char *nl = strchr(tmpl, '\n');
    if (v0 == NULL || v1 == NULL || d1 == NULL || nl == NULL || nl > v0) {
        return -1;
    }
    const char *stop = tmpl + strlen(tmpl);

    sink_t s = { out, cap, 0, 0 };
    out[0] = '\0';

    /* The VRML header has to stay the first line. */
    put(&s, tmpl, (size_t)(nl + 1 - tmpl));
    putf(&s, "\n# GENERATED by tools/worldgen from jundia_fleet.wbt with %u "
             "vessel(s).\n# Do not edit; run `make webots-worlds`.\n", n);
    put(&s, nl + 1, (size_t)(v0 - (nl + 1)));

    /* Vessel 0, the coordinator, unchanged. */
    put(&s, v0, (size_t)(v1 - v0));

    if (n >= 2) {
        put(&s, v1, (size_t)(stop - v1));
    }
    for (size_t k = 2; k < n; k++) {
        put(&s, "\n", 1);
        emit_copy(&s, d1, (size_t)(stop - d1), k);
    }

    return s.full ? -1 : (long)s.len;
}
